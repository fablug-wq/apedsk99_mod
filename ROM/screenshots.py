"""Screenshots of TI-NET TERM in the emulator (co-simulated APEDSK99, fake BBS)
-> docs/screenshots/*.png.   TI99HEADLESS=... python3 ROM/screenshots.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import test_rom as tr                                     # noqa: E402

OUT = os.path.join(tr.REPO, "docs", "screenshots")
os.makedirs(OUT, exist_ok=True)
rig = tr.tc.Rig()
try:
    with tr.th.Machine(tr.ROM, disk="NONE", cards=[rig.card()]) as m:
        m.menu(2)
        tr.wait_for(m, "ADDRESS BOOK", 300)
        for name, host in (("Local test BBS", tr.HOST), ("Cellar", "cellar.example.org"),
                           ("Retropoint", "retro.example.net:2323")):
            m.type(host)
            m.press("FCTN", "8")
            tr.wait_for(m, "NAME:")
            m.type(name + "\r")
            tr.wait_for(m, "Added")
        m.press("FCTN", "6")
        tr.wait_for(m, "Y/N")
        m.type("Y")
        tr.wait_for(m, "Saved")
        m.press("FCTN", "X")
        m.screenshot(os.path.join(OUT, "1-address-book.png"))
        m.type("\r")
        tr.wait_for(m, "READY")
        m.type("Hello from the TI\r")
        tr.wait_for(m, "Hello from the TI")
        m.frames(30)
        m.screenshot(os.path.join(OUT, "2-session.png"))
        m.type("ANSI\r")
        tr.wait_for(m, "ANSI DONE")
        m.frames(30)
        m.screenshot(os.path.join(OUT, "3-ansi-page.png"))
        m.press("FCTN", "9")
        tr.wait_for(m, "H=HANG UP")
        m.screenshot(os.path.join(OUT, "4-session-menu.png"))
        m.type("H")
        tr.wait_for(m, "ADDRESS BOOK")
        m.press("FCTN", "9")
        tr.wait_for(m, "OPTIONS")
        m.type("5")
        m.screenshot(os.path.join(OUT, "5-options.png"))
        m.press("FCTN", "9")
        tr.wait_for(m, "OR TYPE HOST")
        m.press("FCTN", "X")
        m.type("\r")
        tr.wait64(m, "READY")
        m.type("Hello from the TI\r")
        tr.wait64(m, "Hello from the TI")
        m.frames(30)
        m.screenshot(os.path.join(OUT, "6-session-64.png"))
        m.type("ANSI\r")
        tr.wait64(m, "ANSI DONE")
        m.frames(30)
        m.screenshot(os.path.join(OUT, "7-ansi-page-64.png"))
finally:
    rig.close()
print("\n".join(sorted(os.listdir(OUT))))
