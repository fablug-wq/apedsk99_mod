# a few CP437 letters
ACC = {0x85: ("a", "#.."), 0x8A: ("e", "#.."), 0x82: ("e", "..#"), 0x97: ("u", "#.."), 0x95: ("o", "#.."),
       0x8D: ("i", "#.."), 0xA0: ("a", "..#"), 0xA2: ("o", "..#"), 0xA3: ("u", "..#")}

# box drawing at 3 pixels: single line column 1 / row 3, double columns 0, 2 / rows 2, 4
BOX = {
    179: (1, 1, 0, 0), 180: (1, 1, 1, 0), 191: (0, 1, 1, 0), 192: (1, 0, 0, 1), 193: (1, 0, 1, 1),
    194: (0, 1, 1, 1), 195: (1, 1, 0, 1), 196: (0, 0, 1, 1), 197: (1, 1, 1, 1), 217: (1, 0, 1, 0),
    218: (0, 1, 0, 1), 185: (2, 2, 2, 0), 186: (2, 2, 0, 0), 187: (0, 2, 2, 0), 188: (2, 0, 2, 0),
    200: (2, 0, 0, 2), 201: (0, 2, 0, 2), 202: (2, 0, 2, 2), 203: (0, 2, 2, 2), 204: (2, 2, 0, 2),
    205: (0, 0, 2, 2), 206: (2, 2, 2, 2),
}
W, H = 3, 8


def box(up, down, left, right):
    on = set()
    vd, hd = 2 in (up, down), 2 in (left, right)
    chan = set()
    if vd:
        top = 0 if up == 2 else (2 if hd else 3)
        bot = H - 1 if down == 2 else (4 if hd else 3)
        chan |= {(r, c) for r in range(top, bot + 1) for c in range(0, 3)}
    if hd:
        lft = 0 if left == 2 else 0
        rgt = W - 1 if right == 2 else 2
        if not left == 2 and not vd:
            lft = 1
        if not right == 2 and not vd:
            rgt = 1
        chan |= {(r, c) for r in range(2, 5) for c in range(lft, rgt + 1)}

    def inside(r, c):
        if (r, c) in chan:
            return True
        if r < 0:
            return up == 2 and 0 <= c <= 2
        if r >= H:
            return down == 2 and 0 <= c <= 2
        if c < 0:
            return left == 2 and 2 <= r <= 4
        if c >= W:
            return right == 2 and 2 <= r <= 4
        return False
    for (r, c) in chan:
        if not all(inside(r + dr, c + dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1)):
            on.add((r, c))
    if up == 1:
        on |= {(r, 1) for r in range(0, 4)}
    if down == 1:
        on |= {(r, 1) for r in range(3, H)}
    if left == 1:
        on |= {(3, c) for c in range(0, 2)}
    if right == 1:
        on |= {(3, c) for c in range(1, W)}
    return [sum(0x80 >> c for c in range(W) if (r, c) in on) for r in range(H)]


def rows_to_bytes(rows):
    rows = (rows + [""] * 8)[:8]
    return [sum(0x80 >> i for i, ch in enumerate(r.ljust(3)) if ch == "#") for r in rows]


def glyph3(code):
    ch = chr(code)
    if ch in G:
        return rows_to_bytes(G[ch])
    if code in ACC:
        base, acc = ACC[code]
        b = rows_to_bytes(G[base])
        b[0] = rows_to_bytes(["", acc])[1] >> 0
        return b
    if code in BOX:
        return box(*BOX[code])
    full = 0xE0
    return {176: [0x80, 0, 0x20, 0, 0x80, 0, 0x20, 0], 177: [0xA0, 0x40] * 4, 178: [0x60, 0xE0, 0xC0, 0xE0] * 2,
            219: [full] * 8, 220: [0] * 4 + [full] * 4, 223: [full] * 4 + [0] * 4,
            221: [0xC0] * 8, 222: [0x20] * 8, 250: [0, 0, 0, 0x40, 0, 0, 0, 0]}.get(code, [0] * 8)

