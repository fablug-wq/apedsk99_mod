"""inverse.py - the inverse characters of the 40-column screen.

Text mode has one pattern per character code, and every code 32-255 already
has a glyph (font.py), so inverse video can only use the codes that are never
drawn: 0-31, 127 and the empty places of font.py. They are 49: enough for the
space, the capitals, the digits and 12 punctuation marks. A lower-case letter
in inverse shows as its capital in inverse, as on the terminals of the time;
the other characters show as they are.

  python3 inverse.py 0   -> INVPR: (character, code of its inverse) pairs, for
                            the menu bank, which builds the patterns
  python3 inverse.py 1   -> INVMAP: for 32-126 the code to write in inverse
"""
import sys

import font

SOURCE = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:;-!?/()'>"


def free_codes():
    t = font.table()                        # 96-255
    empty = [c for c in range(96, 256) if not any(t[c - 96])]
    return list(range(32)) + empty


def pairs():
    codes = free_codes()
    assert len(codes) >= len(SOURCE), (len(codes), len(SOURCE))
    return [(ord(ch), code) for ch, code in zip(SOURCE, codes)]


def inverse_map():
    p = dict(pairs())
    out = []
    for c in range(32, 127):
        k = ord(chr(c).upper()) if "a" <= chr(c) <= "z" else c
        out.append(p.get(k, c))
    return out


if __name__ == "__main__":
    if sys.argv[1] == "0":
        print("* inv0.a99 - generated by inverse.py: (character, its inverse code) pairs")
        print("INVPR")
        for ch, code in pairs():
            print("       BYTE >%02X,>%02X" % (ch, code))
        print("       BYTE 0")
        print("       EVEN")
    else:
        print("* inv1.a99 - generated by inverse.py: the code written in inverse, for 32-126")
        print("INVMAP")
        m = inverse_map()
        for i in range(0, len(m), 16):
            print("       BYTE " + ",".join(">%02X" % x for x in m[i:i + 16]))
        print("       EVEN")
