W, H = 6, 8
SC, SR = 2, 3                 # single line: column 2, row 3
DC, DR = (1, 4), (2, 4)       # double lines: columns 1 and 4, rows 2 and 4


def box(up, down, left, right):
    on = set()
    vdouble, hdouble = 2 in (up, down), 2 in (left, right)
    # double strokes: the outline of a channel (cols 1-4 vertical, rows 2-4 horizontal)
    chan = set()
    if vdouble:
        top = 0 if up == 2 else (SR if not hdouble else DR[0])
        bot = H - 1 if down == 2 else (SR if not hdouble else DR[1])
        chan |= {(r, c) for r in range(top, bot + 1) for c in range(DC[0], DC[1] + 1)}
    if hdouble:
        lft = 0 if left == 2 else (SC if not vdouble else DC[0])
        rgt = W - 1 if right == 2 else (SC if not vdouble else DC[1])
        chan |= {(r, c) for r in range(DR[0], DR[1] + 1) for c in range(lft, rgt + 1)}

    def inside(r, c):
        if (r, c) in chan:
            return True
        # beyond the cell edge the channel goes on where a double line leaves the cell
        if r < 0:
            return up == 2 and DC[0] <= c <= DC[1]
        if r >= H:
            return down == 2 and DC[0] <= c <= DC[1]
        if c < 0:
            return left == 2 and DR[0] <= r <= DR[1]
        if c >= W:
            return right == 2 and DR[0] <= r <= DR[1]
        return False
    for (r, c) in chan:
        if not all(inside(r + dr, c + dc) for dr in (-1, 0, 1) for dc in (-1, 0, 1)):
            on.add((r, c))
    # single strokes, up to the centre (or the double channel's near edge)
    if up == 1:
        stop = DR[1] if hdouble else SR
        on |= {(r, SC) for r in range(0, stop + 1)}
    if down == 1:
        start = DR[0] if hdouble else SR
        on |= {(r, SC) for r in range(start, H)}
    if left == 1:
        stop = DC[1] if vdouble else SC
        on |= {(SR, c) for c in range(0, stop + 1)}
    if right == 1:
        start = DC[0] if vdouble else SC
        on |= {(SR, c) for c in range(start, W)}
    return [sum(0x80 >> c for c in range(W) if (r, c) in on) for r in range(H)]


def blocks():
    full = 0xFC
    return {
        176: [0x90, 0, 0x24, 0, 0x90, 0, 0x24, 0],                 # light shade
        177: [0xA8, 0x54] * 4,                                    # medium shade
        178: [0x6C, 0xFC, 0xD8, 0xFC, 0x6C, 0xFC, 0xD8, 0xFC],     # dark shade
        219: [full] * 8, 220: [0] * 4 + [full] * 4, 221: [0xE0] * 8,
        222: [0x1C] * 8, 223: [full] * 4 + [0] * 4,
    }


def table():
    font = {}
    for ch, g in LOWER.items():
        font[ord(ch)] = g
    font[127] = [0] * 8
    font.update(LATIN)
    font.update(SYMBOLS)
    for code, dirs in BOX.items():
        font[code] = box(*dirs)
    font.update(blocks())
    return [font.get(c, [0] * 8) for c in range(96, 256)]


def main():
    print("* font.a99 - generated by font.py: patterns for characters 96-255")
    print("FONT")
    for i, g in enumerate(table()):
        print("       BYTE " + ",".join(">%02X" % b for b in g) + "   * %d" % (96 + i))


if __name__ == "__main__":
    main()
