#!/usr/bin/env python3
"""Generates font64.a99: 4 x 8 patterns for the 64-column mode of TI-NET TERM
(bitmap mode, 4 pixels a character: 64 x 4 = 256).

- ASCII 32-126: Tasword 3 (tasword.py; CC BY-SA 3.0, Damien Guard), glyphs in
  columns 1-3, column 0 is the space between characters; " ^ ` drawn here in
  the same style
- CP437 accented lower case: Tasword letters with accents in rows 0-1
- box drawing, blocks, shades: font3.py (columns 0-2), with column 3 filled
  where a line goes on, so lines join across cells

usage: python3 font64.py > font64.a99
"""
import font3
from tasword import GLYPHS

EXTRA = {
    '"': ["....", ".#.#", ".#.#"],
    "^": ["....", "..#.", ".#.#"],
    "`": ["....", ".#..", "..#."],
}
ACCENT = {"grave": [".#..", "..#."], "acute": ["...#", "..#."], "circ": ["..#.", ".#.#"],
          "diaer": ["....", ".#.#"], "ring": ["..#.", "..#."], "tilde": ["..##", ".##."]}
LATIN = {0x81: ("u", "diaer"), 0x82: ("e", "acute"), 0x83: ("a", "circ"), 0x84: ("a", "diaer"),
         0x85: ("a", "grave"), 0x86: ("a", "ring"), 0x88: ("e", "circ"), 0x89: ("e", "diaer"),
         0x8A: ("e", "grave"), 0x8B: ("i", "diaer"), 0x8C: ("i", "circ"), 0x8D: ("i", "grave"),
         0x93: ("o", "circ"), 0x94: ("o", "diaer"), 0x95: ("o", "grave"), 0x96: ("u", "circ"),
         0x97: ("u", "grave"), 0x98: ("y", "diaer"), 0xA0: ("a", "acute"), 0xA1: ("i", "acute"),
         0xA2: ("o", "acute"), 0xA3: ("u", "acute"), 0xA4: ("n", "tilde")}
CAPS = {0x80: "C", 0x8E: "A", 0x8F: "A", 0x90: "E", 0x99: "O", 0x9A: "U", 0xA5: "N"}   # no room: plain


def bits(rows):
    rows = (list(rows) + ["...."] * 8)[:8]
    return [sum(0x80 >> i for i, ch in enumerate(r) if ch == "#") for r in rows]


def glyph(code):
    ch = chr(code)
    if ch in GLYPHS:
        return bits(GLYPHS[ch])
    if ch in EXTRA:
        return bits(EXTRA[ch])
    if code in LATIN:
        base, acc = LATIN[code]
        rows = list(GLYPHS[base])
        if base == "i":
            rows[1] = "...."                      # dotless
        rows[0:2] = ACCENT[acc]
        return bits(rows)
    if code == 0x87:                              # c cedilla
        rows = list(GLYPHS["c"])
        rows[7] = "..#."
        return bits(rows)
    if code in CAPS:
        return bits(GLYPHS[CAPS[code]])
    g = font3.glyph3(code)
    if 176 <= code <= 223:                        # box drawing, blocks: columns 0-2, join in 3
        return [x | (0x10 if x & 0x20 else 0) for x in g]
    return [x >> 1 for x in g]                    # other symbols: into columns 1-3


def table():
    return [glyph(c) if 32 <= c != 127 else [0] * 8 for c in range(256)]


if __name__ == "__main__":
    print("* font64.a99 - generated by font64.py: 4 x 8 patterns for 64 columns, characters 0-255")
    print("* ASCII from Tasword 3 (CC BY-SA 3.0, Damien Guard: see tasword.py)")
    print("F64ROM")
    for code, b in enumerate(table()):
        print("       BYTE " + ",".join(">%02X" % x for x in b) + "   * %d" % code)
